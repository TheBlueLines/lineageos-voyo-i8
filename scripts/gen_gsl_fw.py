#!/usr/bin/env python3
"""Generate gsl3680_fw.h from the stock kernel Image. The tablet's own firmware
is not published anywhere, so the header is generated instead of checked in."""
import array
import sys

img = open(sys.argv[1], "rb").read()
START, RECORDS = 0x13e1bc0 + 4 * 8, 4818
a = array.array("I")
a.frombytes(img[START:START + RECORDS * 8])
assert a[0] == 0xf0 and a[1] == 0x2, "unexpected firmware start"
with open(sys.argv[2], "w", newline="\n") as f:
    f.write("/* Generated by gen_gsl_fw.py from the stock kernel image. */\n")
    f.write("struct gsl_fw_data {\n\tu32 offset;\n\tu32 val;\n};\n\n")
    f.write("static const struct gsl_fw_data gsl3680_fw[] = {\n")
    for i in range(RECORDS):
        f.write(f"\t{{0x{a[2*i]:02x}, 0x{a[2*i+1]:08x}}},\n")
    f.write("};\n")
